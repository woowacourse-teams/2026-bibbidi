#!/usr/bin/env python3
"""Create a repeatable, schema-free MySQL data dump for a fresh load-test stack."""

import argparse
import hashlib
import uuid
from datetime import date, datetime, timedelta
from pathlib import Path


BASE_ID = 900_000_000
CATALOG_ITEMS = 169
FIXED_TIME = "2026-10-01 00:00:00"
REFRESH_EXPIRES_AT = "2036-01-01 00:00:00"
REFRESH_FAMILY_NAMESPACE = uuid.UUID("6f1c5a52-6a3b-4d9a-9a2e-0d7d1c4a5b10")
ROOT = Path(__file__).resolve().parents[3]
CATALOG_SQL = ROOT / "BE/database/mysql/load_catalog.sql"


def insert_rows(output, table, columns, rows):
    batch = []
    for row in rows:
        batch.append(row)
        if len(batch) == 500:
            output.write(f"INSERT INTO {table} ({columns}) VALUES\n")
            output.write(",\n".join(batch) + ";\n")
            batch.clear()
    if batch:
        output.write(f"INSERT INTO {table} ({columns}) VALUES\n")
        output.write(",\n".join(batch) + ";\n")


def sql_time(index):
    day = datetime(2026, 9, 1) + timedelta(days=index % 30)
    return day.strftime("%Y-%m-%d 12:00:00")


def refresh_token(index):
    # k6의 refreshTokenFor()와 같은 규칙이다. 한 번만 쓰는 토큰이라 번호마다 하나씩 만든다.
    return f"loadtest-refresh-{index}"


def generate(output, users, refresh_sessions):
    output.write("-- Generated by Infra/k6/sql/generate-seed.py. Flyway schema must already exist.\n")
    output.write("USE `bibbidi_loadtest`;\nSET NAMES utf8mb4;\n")
    output.write("SET time_zone = '+00:00';\nSTART TRANSACTION;\n")
    output.write(CATALOG_SQL.read_text(encoding="utf-8").replace("CURRENT_TIMESTAMP", f"'{FIXED_TIME}'"))
    output.write("\n")

    insert_rows(
        output,
        "users",
        "id, nickname, status, role, email, created_at, updated_at",
        (
            f"({BASE_ID + i + 1}, 'loadtest-{i + 1:05d}', 'ACTIVE', 'NORMAL', "
            f"'loadtest-{i + 1:05d}@example.invalid', '{sql_time(i)}', '{sql_time(i)}')"
            for i in range(users)
        ),
    )
    insert_rows(
        output,
        "checklists",
        "id, owner_id, created_at, updated_at",
        (
            f"({BASE_ID + i + 1}, {BASE_ID + i + 1}, '{sql_time(i)}', '{sql_time(i)}')"
            for i in range(users)
        ),
    )
    insert_rows(
        output,
        "checklist_items",
        "id, checklist_id, category_id, source_catalog_item_id, title, status, created_at, updated_at",
        (
            f"({BASE_ID + i * 3 + j + 1}, {BASE_ID + i + 1}, NULL, "
            f"{(i * 3 + j) % CATALOG_ITEMS + 1}, '준비 항목 {(i * 3 + j) % CATALOG_ITEMS + 1}', "
            f"'CONTINUE', '{sql_time(i)}', '{sql_time(i)}')"
            for i in range(users)
            for j in range(3)
        ),
    )
    insert_rows(
        output,
        "appointments",
        "id, checklist_item_id, title, appointment_date, is_done, done_by_checklist_item, created_at, updated_at",
        (
            f"({BASE_ID + i + 1}, {BASE_ID + i * 3 + 1}, '상담 일정', "
            f"'{(date(2030, 1, 1) + timedelta(days=i % 365)).isoformat()}', FALSE, FALSE, "
            f"'{sql_time(i)}', '{sql_time(i)}')"
            for i in range(users)
        ),
    )
    # 서버는 refresh token을 SHA-256 hex로 해시해 찾는다. 같은 값으로 알려진 토큰의 세션을 만든다.
    insert_rows(
        output,
        "refresh_sessions",
        "user_id, family_id, client_type, token_hash, expires_at, revoked_at, rotated_at, created_at, updated_at",
        (
            f"({BASE_ID + n % users + 1}, '{uuid.uuid5(REFRESH_FAMILY_NAMESPACE, str(n))}', 'NATIVE', "
            f"'{hashlib.sha256(refresh_token(n).encode()).hexdigest()}', '{REFRESH_EXPIRES_AT}', NULL, NULL, "
            f"'{FIXED_TIME}', '{FIXED_TIME}')"
            for n in range(refresh_sessions)
        ),
    )
    output.write("COMMIT;\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--users", type=int, choices=(1000, 10000), default=1000)
    parser.add_argument("--refresh-sessions", type=int, default=5000,
                        help="k6의 REFRESH_TOKEN_COUNT와 같아야 한다")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8", newline="\n") as output:
        generate(output, args.users, args.refresh_sessions)
    print(f"{args.users} users, {args.users} checklists, {args.users * 3} items, "
          f"{args.users} appointments, {args.refresh_sessions} refresh sessions -> {args.output}")


if __name__ == "__main__":
    main()
